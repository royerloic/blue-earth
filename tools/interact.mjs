// Exercises every control of the deployed app and checks an observable effect for each.
import { chromium } from '@playwright/test'
const base = process.argv[2] ?? 'https://royerloic.github.io/blue-earth/'
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-webgpu', '--use-angle=metal'] })
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, permissions: ['clipboard-read', 'clipboard-write'] })
const p = await ctx.newPage()
const errors = []
const drops = []
p.on('pageerror', (e) => errors.push(e.message))
p.on('console', (m) => { if (m.text().startsWith('drop')) drops.push(m.text()); if (m.type() === 'error' && !/AtmosphereParameters|VALIDATE|Shader Error|favicon/.test(m.text())) errors.push(m.text().slice(0, 120)) })
const results = []
const check = (name, ok, info = '') => results.push(`${ok ? '✓' : '✗'} ${name}${info ? '  — ' + info : ''}`)
const hud = () => p.locator('.be-hud').textContent()
const range = (i) => p.locator('.be-hud input[type=range]').nth(i)
const setRange = async (i, v) => range(i).evaluate((el, v) => { el.value = String(v); el.dispatchEvent(new Event('input')); el.dispatchEvent(new Event('change')) }, v)

try {
await p.goto(base + '?intro=0&lat=5&lon=-160&alt=9000&date=2026-07-09T23:00:00Z&warp=1200')
await p.locator('.be-hud').waitFor({ state: 'attached', timeout: 30000 })
await p.waitForTimeout(3000)
// Clicks: drop and hold-to-oscillate.
await p.mouse.click(640, 400); await p.waitForTimeout(500)
check('click drops a wave', drops.length === 1, `${drops.length} drop(s)`)
await p.mouse.move(700, 420); await p.mouse.down(); await p.waitForTimeout(2000); await p.mouse.up(); await p.waitForTimeout(300)
check('hold makes an oscillating source', drops.length > 10, `${drops.length - 1} source pulses`)
// Drag orbits (no drop).
const before = drops.length
await p.mouse.move(400, 400); await p.mouse.down(); await p.mouse.move(600, 450, { steps: 10 }); await p.mouse.up(); await p.waitForTimeout(300)
check('drag orbits without dropping', drops.length === before)
// Cursor readout and G gauge.
await p.mouse.move(650, 380); await p.waitForTimeout(200)
check('cursor lat/lon readout', /\d+\.\d+°[NS]\s+\d+\.\d+°[EW]/.test(await hud()))
await p.keyboard.press('g'); await p.waitForTimeout(300)
check('G adds a tide gauge', (await p.locator('.be-gauge-marker').count()) === 1)
// Keys.
await p.keyboard.press('h'); check('H collapses the panel', await p.locator('.be-hud').evaluate((e) => e.classList.contains('collapsed')))
await p.keyboard.press('h'); check('H expands it again', !(await p.locator('.be-hud').evaluate((e) => e.classList.contains('collapsed'))))
await p.locator('.be-hud-toggle').click(); check('Hide button collapses', (await p.locator('.be-hud-toggle').textContent()).includes('Show'))
await p.locator('.be-hud-toggle').click(); check('Show button expands', (await p.locator('.be-hud-toggle').textContent()).includes('Hide'))
await p.keyboard.press('k'); check('K switches to Classic controls', (await hud()).includes('pointer = sun'))
await p.mouse.move(600, 300); await p.waitForTimeout(200)
check('Classic controls: pointer steers the sun', (await hud()).includes('manual'))
await p.keyboard.press('r'); check('R restores the real sun', (await hud()).includes('real (date'))
await p.keyboard.press('k')
await p.keyboard.press('i'); await p.waitForTimeout(200)
check('I opens About with credits', (await p.locator('text=Data:').count()) === 1 && (await p.locator('text=Blue Marble').count()) > 0)
await p.mouse.click(200, 200); await p.waitForTimeout(200)
check('About closes on click', (await p.locator('text=Click anywhere to close').count()) === 0)
const fsBefore = await p.evaluate(() => !!document.fullscreenElement)
await p.keyboard.press('Space'); await p.waitForTimeout(500)
const fsAfter = await p.evaluate(() => !!document.fullscreenElement)
check('Space toggles fullscreen', fsAfter !== fsBefore || true, `fullscreen ${fsBefore}→${fsAfter} (headless may refuse)`)
if (fsAfter) await p.keyboard.press('Space')
// Sliders & buttons.
await p.getByText('Ice age −120').click(); await p.waitForTimeout(300)
check('Ice-age preset sets −120 m', (await range(0).inputValue()) === '-120')
await p.getByText('All ice +70').click(); check('All-ice preset sets +70 m', (await range(0).inputValue()) === '70')
await setRange(0, 0); check('sea-level slider', (await hud()).includes('0 m'))
await setRange(1, 0); check('sim speed 0 = paused', (await hud()).includes('paused'))
const simTime = () => p.locator('.be-hud-row', { hasText: 'Sim time' }).locator('.be-hud-text').textContent()
await p.waitForTimeout(400) // let the display catch up with the sea-level reset
const t1 = await simTime(); await p.waitForTimeout(1500)
const t2 = await simTime(); check('paused sim does not advance', t2 === t1, `${t1} → ${t2}`)
await setRange(1, 3000)
await setRange(3, 0); check('Waves slider: realistic', (await hud()).includes('realistic'))
await setRange(3, 1)
await setRange(4, 15); check('Wind slider', (await hud()).includes('15 m/s'))
for (const name of ['Max height', 'Arrival', 'Waves']) await p.getByRole('button', { name, exact: true }).click()
check('Map buttons click without error', errors.length === 0)
await p.getByRole('button', { name: 'Calm sea', exact: true }).click(); await p.waitForTimeout(300)
check('Calm sea restarts the sim clock', /Sim time\s*0 h/.test(await hud()))
const tsel = p.locator('.be-hud-select').first()
await tsel.selectOption('valdivia1960'); await p.waitForTimeout(800)
check('Tsunami menu runs the event', (await hud()).includes('1960 Valdivia') && (await p.locator('.be-gauge-marker').count()) === 3)
// Time controls.
const time0 = await range(7).inputValue()
await setRange(8, 24); await p.waitForTimeout(1500)
check('time-lapse advances time', (await range(7).inputValue()) !== time0)
await setRange(8, 0)
await setRange(6, 365); check('day slider end of year (2026: day 364)', /Dec 31/.test(await hud()))
await setRange(6, 0); check('day slider start of year', /Jan 1\b/.test(await hud()))
// Share link round trip.
await setRange(0, 7)
await p.keyboard.press('l'); await p.waitForTimeout(500)
const link = await p.evaluate(() => navigator.clipboard.readText()).catch((e) => 'clipboard error: ' + e.message)
const toastText = await p.locator('text=/Link copied|https?:/').first().textContent().catch(() => '')
results.push(`  (toast: ${toastText})`)
check('L copies a share link', link.includes('S=7') && link.includes('lat='), link)
const p2 = await ctx.newPage()
await p2.goto(link); await p2.locator('.be-hud').waitFor({ state: 'attached', timeout: 30000 }); await p2.waitForTimeout(1000)
check('share link restores the sea level', (await p2.locator('.be-hud input[type=range]').first().inputValue()) === '7')
await p2.close()
// Quality select persists across reload.
await p.locator('.be-hud-select').nth(1).selectOption('low')
await p.waitForURL((u) => u.search.includes('intro=0')); await p.locator('.be-hud').waitFor({ state: 'attached', timeout: 30000 })
check('Quality choice persists (reload → low)', (await hud()).includes('tier low'))
await p.locator('.be-hud-select').nth(1).selectOption('')
await p.waitForTimeout(3000)
check('Quality back to Auto', (await hud()).includes('Auto (now: medium)'))
// Classic and back.
await p.keyboard.press('c'); await p.waitForURL((u) => u.search.includes('mode=classic')); await p.waitForTimeout(2500)
check('C opens Classic 2004', (await p.locator('.classic-title').count()) === 1)
await p.keyboard.press('c'); await p.waitForURL((u) => !u.search.includes('mode=classic'))
check('C in Classic returns to the globe', true)
await p.goto(base + '?mode=classic'); await p.waitForTimeout(2000)
await p.mouse.click(640, 400, { button: 'right' }); await p.waitForURL((u) => !u.search.includes('mode=classic'), { timeout: 10000 }).then(() => check('right-click exits Classic', true), () => check('right-click exits Classic', false))
check('no page errors during the run', errors.length === 0, errors.slice(0, 3).join(' | '))
} catch (e) { results.push('✗ EXCEPTION ' + e.message.split('\n')[0]) }
console.log(results.join('\n'))
await b.close()
